export const getMockGroup = (groupId?: string) =>
  MOCK_GROUPS.find((g) => g.id === groupId)

export const getMockExercise = (groupId?: string, exerciseId?: string) => {
  const group = getMockGroup(groupId)
  return {
    group,
    exercise: group?.exercises.find((e) => e.id === exerciseId),
  }
}
